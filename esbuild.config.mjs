import esbuild from "esbuild";

const production = process.argv[2] === "production";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: src/main.tsx
*/`;

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.tsx"],
  bundle: true,
  outfile: "main.js",
  format: "cjs",
  platform: "browser",
  target: "es2020",
  jsx: "automatic",
  jsxImportSource: "preact",
  // Obsidian already ships CodeMirror 6 and lezer. They must stay external so the plugin
  // shares Obsidian's copy (a second bundled copy breaks editor state). Language packages
  // (@codemirror/lang-*) are NOT shipped, so those get bundled.
  external: [
    "obsidian",
    "electron",
    "child_process",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
  ],
  sourcemap: production ? false : "inline",
  treeShaking: true,
  minify: production,
  logLevel: "info",
});

if (production) {
  await context.rebuild();
  await context.dispose();
} else {
  await context.watch();
}
