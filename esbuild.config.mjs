import esbuild from "esbuild";
import fs from "node:fs";
import path from "node:path";

const production = process.argv[2] === "production";

/**
 * Copy the build into the vault's plugin folder.
 *
 * Obsidian loads the plugin from `<vault>/.obsidian/plugins/<id>/`, which is
 * usually a different place from this checkout. Without this step a build
 * lands in the repo and Obsidian keeps running whatever it loaded before,
 * which looks exactly like code that does not work.
 *
 * Set OBSIDIAN_PLUGIN_DIR to that folder (or leave it unset if the folder is
 * already a symlink to this one, in which case nothing needs copying).
 */
const PLUGIN_FILES = ["main.js", "manifest.json", "styles.css"];

function copyToVault() {
  const target = process.env.OBSIDIAN_PLUGIN_DIR;
  if (!target) return;

  try {
    // A symlinked plugin folder already points here, so copying would be a
    // file writing over itself.
    const resolved = fs.realpathSync(target);
    if (resolved === fs.realpathSync(process.cwd())) {
      console.log(`[copy] ${target} is this folder — nothing to copy`);
      return;
    }

    fs.mkdirSync(target, { recursive: true });
    for (const file of PLUGIN_FILES) {
      if (!fs.existsSync(file)) continue;
      fs.copyFileSync(file, path.join(target, file));
    }
    console.log(`[copy] -> ${target}`);
  } catch (err) {
    console.error(`[copy] failed for ${target}:`, err.message);
  }
}

/** Copy after every rebuild, so watch mode keeps the vault in step. */
const copyPlugin = {
  name: "copy-to-vault",
  setup(build) {
    build.onEnd((result) => {
      if (result.errors.length) return;
      copyToVault();
    });
  },
};

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: src/main.tsx
*/`;

// transformers ships a node build and a self-contained web build. Obsidian is
// a browser context, so point at the web bundle and keep the node-only deps
// (onnxruntime-node, sharp) out of the graph entirely.
const transformersWeb = path.resolve(
  "node_modules/@huggingface/transformers/dist/transformers.web.js",
);

const context = await esbuild.context({
  plugins: [copyPlugin],
  banner: { js: banner },
  entryPoints: ["src/main.tsx"],
  bundle: true,
  outfile: "main.js",
  format: "cjs",
  platform: "browser",
  target: "es2020",
  jsx: "automatic",
  jsxImportSource: "preact",
  // Obsidian already ships CodeMirror 6 and lezer. They must stay external so the plugin
  // shares Obsidian's copy (a second bundled copy breaks editor state). Language packages
  // (@codemirror/lang-*) are NOT shipped, so those get bundled.
  alias: {
    "@huggingface/transformers": transformersWeb,
  },
  // Obsidian runs on Electron, so `process.release.name === "node"` is true and
  // transformers takes its Node path: it asks for a filesystem PATH instead of a
  // buffer. The web bundle has no fs, so it cannot produce one and throws
  // "Unable to get model file path or buffer". Forcing the check false makes it
  // use the browser path, which accepts the Response our custom fetch returns.
  define: {
    "process.release.name": JSON.stringify("electron"),
  },
  external: [
    "obsidian",
    // Node-only optional deps pulled in by transformers; unused in the web build.
    "onnxruntime-node",
    "sharp",
    "electron",
    "child_process",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
  ],
  sourcemap: production ? false : "inline",
  treeShaking: true,
  minify: production,
  logLevel: "info",
});

if (production) {
  await context.rebuild();
  await context.dispose();
} else {
  await context.watch();
}
